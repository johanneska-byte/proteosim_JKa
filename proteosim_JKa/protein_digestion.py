import re

enzyme_cleavage_patterns = {
    'LysC': r'(?<=K)',
    'LysN': r'(?=K)',
    'ArgC': r'(?<=R)',
    'Trypsin': r'(?<=[KR])(?!P)',
}


def digest_protein_sequence(protein_seq, cleave_pattern, min_pep_len=5 , max_pep_len=30):
    """
    

    Parameters
    ----------
    protein_seq:    str
        sequence of the protein using the one-letter code, filtered by max and min length

    cleve_pattern:  str
        description of the cleaving pattern of the used restriction enzyme
    Returns
    -------
    list
        list of sequences of the resulting peptides as strings
    """
    peptides = re.split(cleave_pattern, protein_seq)

    filtered_peptides = [pep for pep in peptides if min_pep_len <= len(pep) and len(pep) <= max_pep_len ] # list comprehension for filtering

    return filtered_peptides

def digest_protein_collection(protein_map, cleave_pattern, min_pep_len=5, max_pep_len=30):
    """
    Predicts digestion products for a collection of protein sequences using a specified cleavage pattern.

    Parameters
    ----------
    protein_map : dict
        Dictionary mapping protein identifiers to their amino acid sequences. Keys should be protein_IDs and values should be protein sequences as strings.

    cleave_pattern : str
        String describing the cleavage site.

    min_pep_len : int, optional
        Minimum peptide length to include in the results. Peptides shorter than this value are discarded; Default is 5.

    max_pep_len : int, optional
        Maximum peptide length to include in the results. Peptides longer than this value are discarded; Default is 30.

    Returns
    -------
    dict
        Dictionary mapping each protein identifier to a list of predicted peptide sequences generated by the digestion. Only peptides with lengths between `min_pep_len` and `max_pep_len` are returned.
    """

    peptide_dict = {}

    for protein_ID, sequence in protein_map.items():
        peptide_dict[protein_ID] = digest_protein_sequence(
            sequence, 
            cleave_pattern, 
            min_pep_len, 
            max_pep_len
            )

    return peptide_dict

def compute_sequence_coverage(protein_seq, peptides):
    """
    Reports the sequence coverage of a protein based on a set of detectable peptides.

    Parameters
    ----------
    protein_seq : str
        Amino acid sequence of the protein.

    peptides : list of str
        List of peptide sequences detected or predicted to be detectable by mass spectrometry.

    Returns
    -------
    float
        Percentage of amino acid residues in the protein sequence that are covered by at least one peptide. The value is reported as a number between 0 and 100; 100 indicates complete sequence coverage.
    """
    
    coverage = sum(len(peptides)for peptides in peptides) / len(protein_seq) * 100
    return coverage


